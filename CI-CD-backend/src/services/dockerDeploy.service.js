/**
 * Generate production Dockerfile content based on project runtime
 */
export const generateDockerfileContent = (projectPath, port = 5000) => {
  let files = [];
  try {
    files = fs.readdirSync(projectPath);
  } catch (e) {
    files = [];
  }

  // 1. Node.js project (package.json)
  if (files.includes("package.json")) {
    let startCmd = 'CMD ["npm", "start"]';
    try {
      const pkg = JSON.parse(fs.readFileSync(path.join(projectPath, "package.json"), "utf8"));
      if (pkg.scripts?.start) {
        startCmd = 'CMD ["npm", "start"]';
      } else if (pkg.scripts?.dev) {
        startCmd = 'CMD ["npm", "run", "dev"]';
      } else if (pkg.main && files.includes(pkg.main)) {
        startCmd = `CMD ["node", "${pkg.main}"]`;
      } else if (files.includes("server.js")) {
        startCmd = 'CMD ["node", "server.js"]';
      } else if (files.includes("app.js")) {
        startCmd = 'CMD ["node", "app.js"]';
      } else if (files.includes("index.js")) {
        startCmd = 'CMD ["node", "index.js"]';
      }
    } catch (e) {}

    return `# Auto-generated by CloudOps CI/CD Orchestrator
FROM node:22-alpine

WORKDIR /app

# Install dependencies first for optimal Docker layer caching
COPY package*.json ./
RUN npm install --production=false

# Copy application source code
COPY . .

# Environment & Port configuration
ENV PORT=${port}
EXPOSE ${port}

# Support require() on ES Modules seamlessly across Node.js (resolves ERR_REQUIRE_ESM)
ENV NODE_OPTIONS="--experimental-require-module"

# Start the application
${startCmd}
`;
  }

  // 2. Python project (requirements.txt / Pipfile / *.py)
  if (files.includes("requirements.txt") || files.includes("Pipfile") || files.some(f => f.endsWith(".py"))) {
    let entrypoint = "main.py";
    let runCommand = `CMD ["python", "main.py"]`;

    if (files.includes("manage.py")) {
      runCommand = `CMD ["python", "manage.py", "runserver", "0.0.0.0:${port}"]`;
    } else if (files.includes("main.py")) {
      runCommand = `CMD ["python", "main.py"]`;
    } else if (files.includes("app.py")) {
      runCommand = `CMD ["python", "app.py"]`;
    } else if (files.includes("server.py")) {
      runCommand = `CMD ["python", "server.py"]`;
    } else {
      const pyFile = files.find(f => f.endsWith(".py"));
      if (pyFile) runCommand = `CMD ["python", "${pyFile}"]`;
    }

    return `# Auto-generated by CloudOps CI/CD Orchestrator
FROM python:3.10-slim

WORKDIR /app

# Install system dependencies
RUN apt-get update && apt-get install -y --no-install-recommends gcc && rm -rf /var/lib/apt/lists/*

# Install python dependencies
${files.includes("requirements.txt") ? "COPY requirements.txt ./\nRUN pip install --no-cache-dir -r requirements.txt" : "# No requirements.txt found"}

# Copy application source code
COPY . .

ENV PORT=${port}
EXPOSE ${port}

${runCommand}
`;
  }

  // 3. Golang project (go.mod)
  if (files.includes("go.mod")) {
    return `# Auto-generated by CloudOps CI/CD Orchestrator
FROM golang:1.21-alpine AS builder

WORKDIR /app
COPY go.mod go.sum* ./
RUN go mod download

COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -o app .

FROM alpine:latest
WORKDIR /root/
COPY --from=builder /app/app .

ENV PORT=${port}
EXPOSE ${port}
CMD ["./app"]
`;
  }

  // 4. Default Static / Nginx fallback
  return `# Auto-generated by CloudOps CI/CD Orchestrator
FROM nginx:alpine
COPY . /usr/share/nginx/html
EXPOSE 80
CMD ["nginx", "-g", "daemon off;"]
`;
};

/**
 * Auto-detect project runtime and write Dockerfile if missing locally
 */
export const ensureDockerfile = (projectPath, customDockerfilePath = "./Dockerfile", port = 5000, onLog = () => {}) => {
  const targetPath = path.resolve(projectPath, customDockerfilePath || "./Dockerfile");

  // Check if existing Dockerfile is user-provided or auto-generated by CloudOps
  let isAutoGenerated = false;
  if (fs.existsSync(targetPath)) {
    const existingContent = fs.readFileSync(targetPath, "utf8");
    if (existingContent.includes("# Auto-generated by CloudOps CI/CD Orchestrator")) {
      isAutoGenerated = true;
    } else {
      onLog(`[DOCKER] Existing custom Dockerfile found at: ${path.relative(projectPath, targetPath)} ✓`);
      return { path: targetPath, content: existingContent };
    }
  }

  onLog(`[DOCKER] ${isAutoGenerated ? "Regenerating optimized production Dockerfile (Node 22 LTS / ESM support)..." : "No Dockerfile found in repository. Auto-detecting project type..."}`);
  const content = generateDockerfileContent(projectPath, port);
  fs.writeFileSync(targetPath, content, "utf8");
  onLog(`[DOCKER] 📄 Generated production Dockerfile for backend on port ${port} ✓`);

  // Ensure local .dockerignore exists
  try {
    const dockerIgnorePath = path.resolve(projectPath, ".dockerignore");
    if (!fs.existsSync(dockerIgnorePath)) {
      fs.writeFileSync(dockerIgnorePath, "node_modules\n.git\n.env\nnpm-debug.log\n", "utf8");
    }
  } catch (e) {}

  return { path: targetPath, content };
};

/**
 * Format environment variables into Docker --env-file or -e arguments
 */
export const buildEnvArgs = (envVars = []) => {
  if (!Array.isArray(envVars) || envVars.length === 0) return "";

  return envVars
    .filter((ev) => ev && ev.key && ev.key.trim())
    .map((ev) => {
      const cleanKey = ev.key.trim().replace(/[^a-zA-Z0-9_]/g, "");
      const rawVal = ev.value !== undefined ? String(ev.value) : "";
      const escapedVal = rawVal.replace(/"/g, '\\"');
      return `-e ${cleanKey}="${escapedVal}"`;
    })
    .join(" ");
};

/**
 * Build .env file string from environment variables array
 */
export const formatDotEnvString = (envVars = []) => {
  if (!Array.isArray(envVars) || envVars.length === 0) return "";

  return envVars
    .filter((ev) => ev && ev.key && ev.key.trim())
    .map((ev) => {
      const cleanKey = ev.key.trim().replace(/[^a-zA-Z0-9_]/g, "");
      const val = ev.value !== undefined ? String(ev.value) : "";
      return `${cleanKey}=${val}`;
    })
    .join("\n");
};

/**
 * Run shell command promise wrapper
 */
const runCommandAsync = (cmd, cwd, onLog) => {
  return new Promise((resolve, reject) => {
    exec(cmd, { cwd }, (error, stdout, stderr) => {
      if (stdout) {
        stdout.split("\n").forEach((line) => {
          if (line.trim()) onLog(`[DOCKER] ${line}`);
        });
      }
      if (stderr && !stderr.includes("WARNING")) {
        stderr.split("\n").forEach((line) => {
          if (line.trim()) onLog(`[DOCKER] ${line}`);
        });
      }
      if (error) {
        reject(error);
      } else {
        resolve(stdout);
      }
    });
  });
};

/**
 * Deploy Docker container locally (if Docker daemon is running on the host)
 */
export const deployDockerLocal = async ({
  projectPath,
  repoName,
  dockerfilePath = "./Dockerfile",
  port = 5000,
  envVars = [],
  onLog = () => {},
}) => {
  const containerName = `cloudops-${repoName.toLowerCase().replace(/[^a-z0-9-]/g, "-")}`;
  const imageName = `${containerName}:latest`;

  onLog(`[DOCKER] Initializing Docker backend container for "${repoName}" on local daemon...`);

  // 1. Ensure Dockerfile
  ensureDockerfile(projectPath, dockerfilePath, port, onLog);

  // 2. Stop and remove old container if running
  try {
    onLog(`[DOCKER] Stopping and removing any previous container "${containerName}"...`);
    await runCommandAsync(`docker rm -f ${containerName}`, projectPath, () => {});
    onLog(`[DOCKER] Previous container removed ✓`);
  } catch (e) {
    // No previous container, safe to ignore
  }

  // 3. Build Docker Image
  onLog(`[DOCKER] Building Docker image "${imageName}"...`);
  await runCommandAsync(`docker build -t ${imageName} -f ${dockerfilePath} .`, projectPath, onLog);
  onLog(`[DOCKER] Docker image "${imageName}" built successfully ✓`);

  // 4. Run Docker Container with environment variables
  const envFlags = buildEnvArgs(envVars);
  onLog(`[DOCKER] Starting container "${containerName}" mapping host port ${port} -> container ${port}...`);

  const runCmd = `docker run -d --name ${containerName} --restart unless-stopped -p ${port}:${port} ${envFlags} ${imageName}`;
  const runOutput = await runCommandAsync(runCmd, projectPath, onLog);
  const containerId = (runOutput || "").trim().substring(0, 12);

  onLog(`[DOCKER] Container "${containerName}" is running! (ID: ${containerId}) ✓`);

  const deployedUrl = `http://localhost:${port}`;

  onLog(`[DEPLOY] ====================================================`);
  onLog(`[DEPLOY] 🎉 DOCKER BACKEND DEPLOYMENT SUCCESSFUL!`);
  onLog(`[DEPLOY] Container: ${containerName} (${containerId})`);
  onLog(`[DEPLOY] Live API URL: ${deployedUrl}`);
  onLog(`[DEPLOY] Port: ${port} • Environment Variables Injected: ${envVars.length}`);
  onLog(`[DEPLOY] ====================================================`);

  return {
    containerId,
    containerName,
    deployedUrl,
    port,
  };
};

/**
 * Deploy Docker container to remote EC2 over SSH
 */
export const deployDockerRemoteSSH = async ({
  ssh,
  sshUsername,
  repoName,
  targetDir,
  port = 5000,
  envVars = [],
  dockerfileContent,
  onLog = () => {},
}) => {
  const containerName = `cloudops-${repoName.toLowerCase().replace(/[^a-z0-9-]/g, "-")}`;
  const imageName = `${containerName}:latest`;

  onLog(`[DOCKER] Checking Docker engine on EC2 host...`);
  const dockerCheck = await ssh.execCommand("command -v docker", { cwd: `/home/${sshUsername}` });
  if (!dockerCheck.stdout || dockerCheck.stdout.trim() === "") {
    onLog(`[DOCKER] Docker not installed on EC2. Auto-installing docker.io...`);
    const installDockerCmd = `sudo apt-get update && sudo apt-get install -y docker.io && sudo systemctl start docker && sudo systemctl enable docker && sudo usermod -aG docker ${sshUsername} || true`;
    const installRes = await ssh.execCommand(installDockerCmd, { cwd: `/home/${sshUsername}` });
    if (installRes.stdout) onLog(`[DOCKER] ${installRes.stdout}`);
    onLog(`[DOCKER] Docker engine installed and started ✓`);
  } else {
    onLog(`[DOCKER] Docker engine is active on EC2 (${dockerCheck.stdout.trim()}) ✓`);
    await ssh.execCommand("sudo systemctl start docker || true", { cwd: `/home/${sshUsername}` });
  }

  // Write .env file
  const hasPortVar = envVars.some((ev) => ev.key === "PORT");
  const finalEnvVars = hasPortVar ? envVars : [...envVars, { key: "PORT", value: String(port) }];
  const dotEnvContent = formatDotEnvString(finalEnvVars);
  onLog(`[DOCKER] Securing ${finalEnvVars.length} environment variables into ${targetDir}/.env...`);
  await ssh.execCommand(`cat << 'CLOUDOPS_EOF' > ${targetDir}/.env\n${dotEnvContent}\nCLOUDOPS_EOF`, { cwd: targetDir });
  await ssh.execCommand(`chmod 600 ${targetDir}/.env`, { cwd: targetDir });
  onLog(`[DOCKER] Environment variables written to .env ✓`);

  // Ensure .dockerignore exists on EC2 to avoid copying host node_modules into container
  const checkDockerIgnore = await ssh.execCommand(`[ -f "${targetDir}/.dockerignore" ] && echo "exists" || echo "missing"`, { cwd: targetDir });
  if (checkDockerIgnore.stdout.trim() !== "exists") {
    await ssh.execCommand(`cat << 'CLOUDOPS_EOF' > ${targetDir}/.dockerignore\nnode_modules\n.git\n.env\nnpm-debug.log\nCLOUDOPS_EOF`, { cwd: targetDir });
    onLog(`[DOCKER] Optimized .dockerignore created on EC2 ✓`);
  }

  // Ensure Dockerfile exists and is up to date on EC2
  const checkGitTracked = await ssh.execCommand(`git ls-files --error-unmatch Dockerfile 2>/dev/null && echo "tracked" || echo "untracked"`, { cwd: targetDir });
  const isTracked = checkGitTracked.stdout.trim() === "tracked";

  if (!isTracked) {
    onLog(`[DOCKER] Applying latest CloudOps production Dockerfile (Node 22 LTS / ESM support) to EC2...`);
    await ssh.execCommand(`cat << 'CLOUDOPS_EOF' > ${targetDir}/Dockerfile\n${dockerfileContent}\nCLOUDOPS_EOF`, { cwd: targetDir });
    onLog(`[DOCKER] Production Dockerfile updated on EC2 ✓`);
  } else {
    onLog(`[DOCKER] Existing custom Dockerfile from git repository detected ✓`);
  }

  // Stop previous container
  onLog(`[DOCKER] Stopping previous container "${containerName}" if present...`);
  await ssh.execCommand(`sudo docker rm -f ${containerName} || true`, { cwd: targetDir });

  // Build Docker Image on EC2
  onLog(`[DOCKER] Building Docker image "${imageName}" on EC2...`);
  const buildResult = await ssh.execCommand(`sudo docker build -t ${imageName} .`, { cwd: targetDir });
  if (buildResult.stdout) {
    buildResult.stdout.split("\n").filter(Boolean).forEach((line) => onLog(`[DOCKER] ${line}`));
  }
  if (buildResult.code !== 0) {
    if (buildResult.stderr) onLog(`[ERROR] ${buildResult.stderr}`);
    throw new Error(`Docker build failed on EC2 with code ${buildResult.code}: ${buildResult.stderr || buildResult.stdout}`);
  }
  onLog(`[DOCKER] Docker image "${imageName}" built successfully ✓`);

  // Run container
  onLog(`[DOCKER] Starting container "${containerName}" mapping port ${port}:${port}...`);
  const runCmd = `sudo docker run -d --name ${containerName} --restart unless-stopped -p ${port}:${port} --env-file .env ${imageName}`;
  const runResult = await ssh.execCommand(runCmd, { cwd: targetDir });
  if (runResult.code !== 0) {
    if (runResult.stderr) onLog(`[ERROR] ${runResult.stderr}`);
    throw new Error(`Failed to start Docker container on EC2: ${runResult.stderr || runResult.stdout}`);
  }

  const containerId = (runResult.stdout || "").trim().substring(0, 12);
  onLog(`[DOCKER] Container created on EC2 (ID: ${containerId}). Waiting 4s to verify runtime stability...`);

  // Wait 4 seconds to verify container actually stays up and doesn't crash on startup
  await new Promise((resolve) => setTimeout(resolve, 4000));

  // ALWAYS fetch container logs so user sees what their backend is doing
  const containerLogs = await ssh.execCommand(`sudo docker logs --tail 40 ${containerName}`, { cwd: targetDir });
  if (containerLogs.stdout && containerLogs.stdout.trim()) {
    onLog(`[APP OUTPUT] Application stdout:`);
    containerLogs.stdout.trim().split("\n").forEach((line) => onLog(`[APP] ${line}`));
  }
  if (containerLogs.stderr && containerLogs.stderr.trim()) {
    onLog(`[APP OUTPUT] Application stderr:`);
    containerLogs.stderr.trim().split("\n").forEach((line) => onLog(`[APP ERROR] ${line}`));
  }

  // Inspect container state
  const postCheck = await ssh.execCommand(
    `sudo docker inspect --format="{{.State.Status}} {{.State.Running}} {{.State.ExitCode}}" ${containerName}`,
    { cwd: targetDir }
  );
  const statusParts = (postCheck.stdout || "").trim().split(" ");
  const currentStatus = statusParts[0];
  const isRunning = statusParts[1];
  const exitCode = statusParts[2];

  const psCheck = await ssh.execCommand(`sudo docker ps --filter "name=${containerName}" --format "{{.Status}}"`, { cwd: targetDir });
  const psStatus = (psCheck.stdout || "").trim();

  const isFailing = currentStatus === "exited" || currentStatus === "restarting" || isRunning !== "true" || psStatus.toLowerCase().includes("restart");

  if (isFailing) {
    // Stop the restarting container so it does not burn EC2 CPU in an infinite loop
    await ssh.execCommand(`sudo docker stop ${containerName} || true`, { cwd: targetDir });

    onLog(`[ERROR] ====================================================`);
    onLog(`[ERROR] 💥 CONTAINER FAILED TO STAY RUNNING!`);
    onLog(`[ERROR] Status: "${currentStatus}" • Docker PS: "${psStatus}" • Exit Code: ${exitCode || "1"}`);
    onLog(`[ERROR] Check the [APP ERROR] logs printed above for the exact reason.`);
    onLog(`[HINT] Common causes:`);
    onLog(`[HINT] 1. MongoDB Atlas Network Access: In Atlas -> Network Access -> Add IP Address -> Allow 0.0.0.0/0 (so AWS EC2 can connect).`);
    onLog(`[HINT] 2. Missing or incorrect Environment Variables (.env).`);
    if (containerLogs.stderr && containerLogs.stderr.includes("ERR_REQUIRE_ESM")) {
      onLog(`[HINT] 3. ESM Conflict: require() was called on an ES Module package. Node 22 with --experimental-require-module is required.`);
    }
    onLog(`[ERROR] ====================================================`);
    throw new Error(
      `Backend container crashed on startup (Status: ${currentStatus || psStatus}, Exit code: ${exitCode || "1"}). Look at [APP ERROR] logs above for the exact failure reason.`
    );
  }

  onLog(`[DOCKER] Container is healthy, running, and accepting traffic! ✓`);
  const inspectResult = await ssh.execCommand(`sudo docker ps --filter "name=${containerName}" --format "table {{.ID}}\t{{.Status}}\t{{.Ports}}"`, { cwd: targetDir });
  if (inspectResult.stdout) {
    inspectResult.stdout.split("\n").filter(Boolean).forEach((line) => onLog(`[DOCKER] ${line}`));
  }

  return {
    containerId,
    containerName,
    port,
  };
};

/**
 * Fast Sync .env and Restart Docker container on remote EC2 over SSH
 */
export const restartDockerRemoteSSH = async ({
  ssh,
  targetDir,
  containerName,
  port = 5000,
  envVars = [],
  onLog = () => {},
}) => {
  // 1. Rewrite .env file on EC2
  const hasPortVar = envVars.some((ev) => ev.key === "PORT");
  const finalEnvVars = hasPortVar ? envVars : [...envVars, { key: "PORT", value: String(port) }];
  const dotEnvContent = formatDotEnvString(finalEnvVars);
  onLog(`[DOCKER] Securing ${finalEnvVars.length} environment variables into ${targetDir}/.env...`);
  await ssh.execCommand(`cat << 'CLOUDOPS_EOF' > ${targetDir}/.env\n${dotEnvContent}\nCLOUDOPS_EOF`, { cwd: targetDir });
  await ssh.execCommand(`chmod 600 ${targetDir}/.env`, { cwd: targetDir });
  onLog(`[DOCKER] Updated .env file written to host ✓`);

  // 2. Restart container
  onLog(`[DOCKER] Restarting container "${containerName}" with updated variables...`);
  const restartRes = await ssh.execCommand(`sudo docker restart ${containerName}`, { cwd: targetDir });
  if (restartRes.code !== 0) {
    onLog(`[DOCKER] Container was not running. Launching container fresh...`);
    const imageName = `${containerName}:latest`;
    const runCmd = `sudo docker run -d --name ${containerName} --restart unless-stopped -p ${port}:${port} --env-file .env ${imageName}`;
    await ssh.execCommand(runCmd, { cwd: targetDir });
  }

  // 3. Wait 2 seconds to check status
  await new Promise((resolve) => setTimeout(resolve, 2000));
  const psCheck = await ssh.execCommand(`sudo docker ps --filter "name=${containerName}" --format "{{.Status}}"`, { cwd: targetDir });
  const psStatus = (psCheck.stdout || "").trim();

  const isHealthy = psStatus.toLowerCase().includes("up");
  onLog(`[DOCKER] Container status: "${psStatus}" ${isHealthy ? "✓" : "⚠️"}`);

  return {
    success: isHealthy,
    containerName,
    psStatus,
  };
};
